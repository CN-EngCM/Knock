function SelectTrigger({
  className,
  size = "default",
  children,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Trigger> & {
  size?: "sm" | "default"
}) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      data-size={size}
      className={cn(
        "relative flex w-fit cursor-default items-center justify-between gap-(--space-md) rounded-[5px] border-0 bg-[var(--control-select-background)] px-(--space-xl) py-0 shadow-raised text-xs whitespace-nowrap transition-none outline-none select-none before:pointer-events-none before:absolute before:inset-[0.5px] before:rounded-[inherit] before:bg-[linear-gradient(to_bottom,#ffffff09,#ffffff03_1px,transparent_3px)] before:content-[''] enabled:hover:data-[state=closed]:brightness-[1.025] enabled:active:shadow-[inset_0_0_0_100px_var(--state-pressed-overlay),var(--elevation-raised)] enabled:active:brightness-100 data-[state=open]:brightness-100 data-[state=open]:shadow-[inset_0_0_0_100px_var(--state-pressed-overlay),var(--elevation-raised)] disabled:cursor-default disabled:opacity-(--state-disabled-opacity) aria-invalid:shadow-[inset_0_0_0_1px_var(--button-invalid)] data-placeholder:text-muted-foreground data-[size=default]:h-(--size-control-md) data-[size=sm]:h-(--size-control-sm) data-[size=sm]:rounded-[min(var(--radius-md),10px)] *:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-2    [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        className
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon asChild>
        <ChevronDownIcon className="pointer-events-none size-4 text-muted-foreground" />
      </SelectPrimitive.Icon>
    </SelectPrimitive.Trigger>
  )
}

function SelectContent({
  className,
  children,
  position = "item-aligned",
  align = "center",
  ref,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Content>) {
  const overlayRef = useOverlayDensity(ref)
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        data-slot="select-content"
        data-align-trigger={position === "item-aligned"}
        className={cn(
          "relative z-50 max-h-(--radix-select-content-available-height) min-w-40 origin-(--radix-select-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-md bg-popover border border-(--elevation-overlay-border) p-1 text-popover-foreground shadow-overlay data-open:duration-(--motion-quick-in) data-closed:duration-(--motion-quick-out) data-open:ease-(--motion-ease) data-closed:ease-(--motion-ease-exit) data-[align-trigger=true]:animate-none data-open:animate-in data-open:fade-in-0 data-closed:animate-out data-closed:fade-out-0",
          position === "popper" && "data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1",
          className
        )}
        position={position}
        align={align}
        {...props}
        ref={overlayRef}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          data-position={position}
          className="data-[position=popper]:h-(--radix-select-trigger-height) data-[position=popper]:w-full data-[position=popper]:min-w-(--radix-select-trigger-width)"
        >
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  )
}

